                 VALUES (?, NULL, ?, ?, ?, ?, ?, ?, ?, ?, ?)',
                [
                    $notification['id'],
                    $notification['type'],
                    $notification['category'],
                    $notification['title'],
                    $notification['description'],
                    $notification['actionLabel'],
