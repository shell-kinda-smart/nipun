    }

    private function seedDocuments(): void
    {
        $types = ['PAN card', 'Aadhaar card', 'Bank statement', 'Experience letter'];
        foreach ($this->employees as $employee) {
            foreach ($types as $index => $type) {
                $issued = (new \DateTimeImmutable($employee['joinedAt']))
                    ->modify('+' . (30 * ($index + 1)) . ' days')
                    ->format('Y-m-d');
                $expires = (new \DateTimeImmutable($issued))->modify('+' . (365 * 3) . ' days')->format('Y-m-d');
                $status = 'verified';
                if ($type === 'PAN card' && $employee['id'] === 'EMP028') {
                    $status = 'pending';
                }
                $this->app->db->execute(
                    'INSERT INTO documents (id, employee_id, name, type, status, issued_at, expires_at, size_bytes, created_at)
                     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)',
                    [
                        sprintf('DOC-%s-%d', $employee['id'], $index + 1),
                        $employee['id'],
                        $type . ' — ' . $employee['name'],
                        $type,
                        $status,
                        $issued,
                        $expires,
                        120000 + $index * 4096,
                        $this->now(),
                    ],
                );
            }
        }
    }

    /**
