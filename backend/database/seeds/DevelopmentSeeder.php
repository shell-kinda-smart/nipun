/**
 * Development seed.
 *
 * Produces the same fictional dataset the UI was designed around: 51
 * employees across four departments, six payroll periods, anomalies,
 * notifications, documents and an audit trail. Every name, employee id and
 * salary is generated by the deterministic LCG that was ported from the
 * frontend seed, so the demo looks exactly as it did before the backend
 * existed — but now every figure comes from the database.
 *
 * ALL DATA IS FICTIONAL. The passwords are development credentials and
 * must never be used anywhere else.
 */
final class DevelopmentSeeder
{
    /** @var array<int,array<string,mixed>> */
    private array $employees = [];

    private Random $rand;

    private int $counter = 1;

    public function __construct(private App $app)
    {
        $this->rand = new Random(0xC0FFEE);
    }

    /**
     * The tables the seed owns. Clearing them is what `--fresh` does; the
     * migration table is deliberately not in the list.
     */
    public const SEEDED_TABLES = [
        'payslip_lines',
        'payslips',
        'payroll_adjustments',
        'payroll_runs',
        'employee_attendance',
        'employee_bank_details',
        'salary_structures',
        'documents',
        'notifications',
        'anomalies',
        'audit_logs',
        'sessions',
        'rate_limits',
        'billing_invoices',
        'user_preferences',
        'users',
        'employees',
        'departments',
        'payroll_rules',
        'tax_slabs',
        'role_permissions',
        'permissions',
        'roles',
    ];

    /**
     * Clear the seeded tables so the dataset can be loaded again.
     *
     * Explicitly called by `bin/seed.php --fresh` — never silently, and
     * never in a production environment. The order respects the foreign
     * keys, and the migration table is left alone.
     */
    public function reset(): void
    {
        $this->app->db->transaction(function (): void {
            foreach (self::SEEDED_TABLES as $table) {
                $this->app->db->execute('DELETE FROM ' . $table);
            }
        });
    }

    public function run(string $password): array
    {
        $summary = [];

        $summary['roles'] = $this->seedRoles();

        $this->seedDepartments();
        $summary['departments'] = count(self::DEPARTMENTS);

        $this->seedEmployees();
        $summary['employees'] = count($this->employees);

        $summary['users'] = $this->seedUsers($password);

        $this->seedRules();
        $summary['payrollRules'] = count(self::RULES);

        $this->seedSlabs();
        $summary['taxSlabs'] = count(self::SLABS);

        $this->seedAnomalies();
        $summary['anomalies'] = count(self::ANOMALIES);

        $this->seedNotifications();
        $summary['notifications'] = count(self::NOTIFICATIONS);

        $this->seedDocuments();
        $summary['documents'] = count($this->employees) * 4;

        $summary['auditTrail'] = $this->seedAuditTrail();

        $this->seedBilling();
        $summary['invoices'] = 3;

        $summary['payrollRuns'] = $this->seedPayrollRuns();

        return $summary;
    }

    // ── Roles and permissions ─────────────────────────────────────────────

    private function seedRoles(): int
    {
        /** @var array{roles:array<string,array{0:string,1:string}>,permissions:array<string,string>,matrix:array<string,array<int,string>>} $config */
        $config = require dirname(__DIR__) . '/roles.php';

        // Migration 013 writes the same matrix, and `--fresh` clears it
        // again, so every insert here is conditional: the seed has to work
        // both on a database that has been migrated and on one whose matrix
        // was just deleted.
        foreach ($config['permissions'] as $permission => $description) {
            $exists = $this->app->db->selectOne('SELECT COUNT(*) AS c FROM permissions WHERE name = ?', [$permission]);
            if ((int) ($exists['c'] ?? 0) === 0) {
                $this->app->db->execute(
                    'INSERT INTO permissions (name, description) VALUES (?, ?)',
                    [$permission, $description],
                );
            }
        }

        foreach ($config['roles'] as $role => [$label, $description]) {
            $exists = $this->app->db->selectOne('SELECT COUNT(*) AS c FROM roles WHERE name = ?', [$role]);
            if ((int) ($exists['c'] ?? 0) === 0) {
                $this->app->db->execute(
                    'INSERT INTO roles (name, label, description, created_at) VALUES (?, ?, ?, ?)',
                    [$role, $label, $description, $this->now()],
                );
            }
        }

        foreach ($config['matrix'] as $role => $permissions) {
            foreach ($permissions as $permission) {
                $exists = $this->app->db->selectOne(
                    'SELECT COUNT(*) AS c FROM role_permissions WHERE role_name = ? AND permission_name = ?',
                    [$role, $permission],
                );
                if ((int) ($exists['c'] ?? 0) === 0) {
                    $this->app->db->execute(
                        'INSERT INTO role_permissions (role_name, permission_name) VALUES (?, ?)',
                        [$role, $permission],
                    );
                }
            }
        }

        return count($config['roles']);
    }

    // ── Organisation ───────────────────────────────────────────────────────

    private function seedDepartments(): void
    {
        foreach (self::DEPARTMENTS as $department) {
            $this->app->db->execute(
                'INSERT INTO departments (id, name, color, icon, created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?)',
                [$department['id'], $department['name'], $department['color'], $department['icon'], $this->now(), $this->now()],
            );
        }
    }

    private function seedEmployees(): void
    {
        // Three system accounts first, exactly as the frontend seed did.
        $this->employees[] = $this->makeEmployee([
            'desig' => 'Platform Administrator',
            'dept' => 'people',
            'role' => 'admin',
            'performanceRating' => 5,
        ]);
        $this->employees[] = $this->makeEmployee([
            'desig' => 'HR Manager',
            'dept' => 'people',
            'role' => 'hr',
            'performanceRating' => 5,
        ]);
        $this->employees[] = $this->makeEmployee([
            'desig' => 'Finance Manager',
            'dept' => 'people',
            'role' => 'finance',
            'performanceRating' => 5,
        ]);

        foreach (self::DEPARTMENTS as $department) {
            $designations = [];
            foreach (self::DESIGNATIONS as $name => $band) {
                $isSystem = in_array($name, ['Platform Administrator', 'HR Manager', 'Finance Manager'], true);
                if (! $isSystem && in_array($department['id'], $band['dept'], true)) {
                    $designations[] = $name;
                }
            }
            for ($i = 0; $i < 12; $i++) {
                $desig = $this->rand->pick($designations);
                $status = $this->rand->next() < 0.04
                    ? 'on_leave'
                    : ($this->rand->next() < 0.04 ? 'probation' : 'active');
                $this->employees[] = $this->makeEmployee([
                    'desig' => $desig,
                    'dept' => $department['id'],
                    'status' => $status,
                ]);
            }
        }

        $now = $this->now();
        $employees = new EmployeeRepository($this->app->db);

        foreach ($this->employees as $employee) {
            $this->app->db->execute(
                'INSERT INTO employees
                    (id, first_name, last_name, email, phone, department_id, designation,
                     employment_status, employment_type, date_of_joining, date_of_birth, gender,
                     app_role, performance_rating, avatar_seed, is_deleted, created_at, updated_at)
                 VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 0, ?, ?)',
                [
                    $employee['id'],
                    $employee['firstName'],
                    $employee['lastName'],
                    $employee['email'],
                    $employee['phone'],
                    $employee['departmentId'],
                    $employee['designation'],
                    $employee['status'],
                    'full_time',
                    $employee['joinedAt'],
                    null,
                    null,
                    $employee['role'],
                    $employee['performanceRating'],
                    $employee['avatarSeed'],
                    $now,
                    $now,
                ],
            );

            // Compensation is versioned. The base structure starts when the
            // employee joined; half the workforce receives a revision
            // effective 1 July 2026, which is what gives the payroll trend
            // its step up.
            $employees->addSalaryVersion(
                $employee['id'],
                $employee['joinedAt'],
                $employee['salaryPaise'],
                Money::toMinor($employee['ctcAnnual']),
                null,
            );

            $this->app->db->execute(
                'INSERT INTO employee_bank_details (employee_id, effective_from, effective_to, account_number, ifsc, bank_name, created_at)
                 VALUES (?, ?, NULL, ?, ?, ?, ?)',
                [
                    $employee['id'],
                    $employee['joinedAt'],
                    $employee['bank']['account'],
                    $employee['bank']['ifsc'],
                    $employee['bank']['bankName'],
                    $now,
                ],
            );

            // Attendance is recorded for every period the demo runs payroll
            // for, so a payslip shows the days the employee actually worked
            // instead of a default.
            foreach (self::PAYROLL_PERIODS as $index => [$periodYear, $periodMonth]) {
                $present = max(0, min(22, $employee['attendance']['present'] - ($index % 3)));
                $absent = max(0, min(22 - $present, $employee['attendance']['absent']));
                $leaves = max(0, min(22 - $present - $absent, $employee['attendance']['leaves']));

                $this->app->db->execute(
                    'INSERT INTO employee_attendance
                        (employee_id, period_month, period_year, working_days, days_present, days_absent, days_late, leaves, created_at)
                     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)',
                    [
                        $employee['id'],
                        $periodMonth,
                        $periodYear,
                        22,
                        $present,
                        $absent,
                        $employee['attendance']['late'],
                        $leaves,
                        $now,
                    ],
                );
            }
        }

        // The July 2026 revision.
        foreach ($this->employees as $index => $employee) {
            if ($index % 2 !== 0) {
                continue;
            }
            $components = $employee['salaryPaise'];
            $components['basic_paise'] = (int) round($components['basic_paise'] * 1.06);
            $components['hra_paise'] = (int) round($components['hra_paise'] * 1.06);
            $components['special_allowance_paise'] = (int) round($components['special_allowance_paise'] * 1.06);

            // `ctc_annual_paise` is in paise, and so are the components, so
            // the annual figure is twelve times the revised monthly gross.
            $monthlyGrossPaise = $components['basic_paise']
                + $components['hra_paise']
                + $components['special_allowance_paise']
                + $components['travel_allowance_paise'];

            $employees->addSalaryVersion(
                $employee['id'],
                '2026-07-01',
                $components,
                $monthlyGrossPaise * 12,
                null,
            );
        }
    }

    /**
     * @param array<string,mixed> $options
     * @return array<string,mixed>
     */
    private function makeEmployee(array $options): array
    {
        $band = self::DESIGNATIONS[$options['desig']];
        $ctc = $this->rand->between($band['min'] * 100000, $band['max'] * 100000);

        $name = $this->makeName();
        $id = 'EMP' . str_pad((string) $this->counter++, 3, '0', STR_PAD_LEFT);
        $salary = $this->makeSalary($ctc);

        $phone = $this->makePhone();
        $joinedAt = $this->randomJoinDate();
        $bank = $this->makeBank();
        $attendance = $this->makeAttendance();
        $rating = $options['performanceRating'] ?? $this->rand->intBetween(3, 5);

        [$first, $last] = explode(' ', $name, 2);

        return [
            'id' => $id,
            'firstName' => $first,
            'lastName' => $last,
            'name' => $name,
            'email' => strtolower($first . '.' . $last) . '@paylens.co',
            'phone' => $phone,
            'designation' => $options['desig'],
            'departmentId' => $options['dept'],
            'role' => $options['role'] ?? 'employee',
            'status' => $options['status'] ?? 'active',
            'joinedAt' => $joinedAt,
            'ctcAnnual' => Random::round($ctc),
            'salary' => $salary,
            'salaryPaise' => [
                'basic_paise' => Money::toMinor($salary['basic']),
                'hra_paise' => Money::toMinor($salary['hra']),
                'special_allowance_paise' => Money::toMinor($salary['specialAllowance']),
                'travel_allowance_paise' => Money::toMinor($salary['travelAllowance']),
                'pf_paise' => 0,
                'professional_tax_paise' => 0,
            ],
            'bank' => $bank,
            'avatarSeed' => strtolower(preg_replace('/\s+/', '-', $name)),
            'attendance' => $attendance,
            'performanceRating' => $rating,
        ];
    }

    private function makeName(): string
    {
        return $this->rand->pick(self::FIRST_NAMES) . ' ' . $this->rand->pick(self::LAST_NAMES);
    }

    private function makePhone(): string
    {
        return sprintf(
            '+91 %d %d',
            $this->rand->intBetween(70000, 99999),
            $this->rand->intBetween(10000, 99999),
        );
    }

    /** @return array<string,mixed> */
    private function makeSalary(float $annualCtc): array
    {
        $monthly = $annualCtc / 12;
        $basic = $monthly * 0.5;
        $hra = $basic * 0.5;

        $travel = $this->rand->next() < 0.4 ? $this->rand->intBetween(1500, 4000) : 0;

        return [
            'basic' => Random::round($basic),
            'hra' => Random::round($hra),
            'specialAllowance' => Random::round($monthly - $basic - $hra),
            'travelAllowance' => $travel,
            'pf' => min(Random::round($basic * 0.12), 1800),
            'professionalTax' => 200,
        ];
    }

    /** @return array<string,string> */
    private function makeBank(): array
    {
        $account = (string) $this->rand->intBetween(100000000, 999999999);
        $prefix = $this->rand->pick(['HDFC', 'ICIC', 'SBIN', 'AXIS', 'KOTK']);
        $number = $this->rand->intBetween(100000, 999999);
        return [
            'account' => $account,
            'ifsc' => $prefix . '0' . $number,
            'bankName' => $this->rand->pick(self::BANK_NAMES),
        ];
    }

    /** @return array<string,int> */
    private function makeAttendance(): array
    {
        return [
            'present' => $this->rand->intBetween(18, 22),
            'absent' => $this->rand->intBetween(0, 2),
            'late' => $this->rand->intBetween(0, 3),
            'leaves' => $this->rand->intBetween(0, 2),
        ];
    }

    private function randomJoinDate(): string
    {
        $month = $this->rand->intBetween(1, 12);
        $year = $this->rand->intBetween(2019, 2025);
        $day = $this->rand->intBetween(1, 28);
        return sprintf('%04d-%02d-%02d', $year, $month, $day);
    }

    // ── Users ──────────────────────────────────────────────────────────────

    /**
     * The demo accounts.
     *
     * One account per role. The first three employees are the admin, HR and
     * finance accounts; the sample employee is the employee login, and a
     * further employee carries the payroll approver role so the approval
     * duty can be exercised separately from preparation.
     *
     * The index is the employee's position in the seeded roster.
     */
    private const DEMO_ACCOUNTS = [
        ['index' => 0, 'role' => 'admin'],
        ['index' => 1, 'role' => 'hr'],
        ['index' => 2, 'role' => 'finance'],
        ['index' => 5, 'role' => 'employee'],
        ['index' => 6, 'role' => 'approver'],
    ];

    private function seedUsers(string $password): int
    {
        $hash = password_hash($password, PASSWORD_DEFAULT);
        $created = 0;

        foreach (self::DEMO_ACCOUNTS as $account) {
            $employee = $this->employees[$account['index']] ?? null;
            if ($employee === null) {
                continue;
            }
            $this->createUser($hash, $account['role'], $employee);
            $created++;
        }

        return $created;
    }

    /**
     * Create any demo account that is missing.
     *
     * A database seeded before a role existed keeps working, but it is
     * missing the account for that role. This adds exactly the accounts that
     * are missing and leaves every existing one alone, so an existing
     * database can be brought up to date without being reseeded.
     *
     * @return int The number of accounts created.
     */
    public function ensureDemoAccounts(string $password): int
    {
        $rows = $this->app->db->select(
            'SELECT id, first_name, last_name, email, avatar_seed
             FROM employees WHERE is_deleted = 0 ORDER BY id',
        );
        if ($rows === []) {
            return 0;
        }

        $hash = password_hash($password, PASSWORD_DEFAULT);
        $created = 0;

        foreach (self::DEMO_ACCOUNTS as $account) {
            $row = $rows[$account['index']] ?? null;
            if ($row === null) {
                continue;
            }

            $exists = $this->app->db->selectOne(
                'SELECT COUNT(*) AS c FROM users WHERE email = ?',
                [(string) $row['email']],
            );
            if ((int) ($exists['c'] ?? 0) > 0) {
                continue;
            }

            $this->createUser($hash, $account['role'], [
                'email' => (string) $row['email'],
                'name' => trim((string) $row['first_name'] . ' ' . (string) $row['last_name']),
                'id' => (string) $row['id'],
                'avatarSeed' => (string) $row['avatar_seed'],
            ]);
            $created++;
        }

        return $created;
    }

    /**
     * @param array<string,mixed> $employee
     */
    private function createUser(string $hash, string $role, array $employee): void
    {
        $this->app->db->execute(
            'INSERT INTO users (email, password_hash, name, role, status, employee_id, avatar_seed, failed_login_count, created_at, updated_at)
             VALUES (?, ?, ?, ?, ?, ?, ?, 0, ?, ?)',
            [
                $employee['email'],
                $hash,
                $employee['name'],
                $role,
                'active',
                $employee['id'],
                $employee['avatarSeed'],
                $this->now(),
                $this->now(),
            ],
        );
    }

