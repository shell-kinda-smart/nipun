    // ── Operational records ────────────────────────────────────────────────

    private function seedAnomalies(): void
    {
        $employeeIds = array_map(static fn (array $e): string => $e['id'], $this->employees);
        foreach (self::ANOMALIES as $index => $anomaly) {
            $employeeId = $anomaly['employeeIndex'] === null ? null : ($employeeIds[$anomaly['employeeIndex']] ?? null);
            $this->app->db->execute(
                'INSERT INTO anomalies
                    (id, type, severity, status, employee_id, payroll_run_id, title, description,
                     risk_score, amount_paise, assigned_to, detected_at, created_at, updated_at)
                 VALUES (?, ?, ?, ?, ?, NULL, ?, ?, ?, ?, ?, ?, ?, ?)',
                [
                    sprintf('A%03d', $index + 1),
                    $anomaly['type'],
                    $anomaly['severity'],
                    $anomaly['status'],
                    $employeeId,
                    $anomaly['title'],
                    $anomaly['description'],
                    $anomaly['risk'],
                    isset($anomaly['amount']) ? Money::toMinor($anomaly['amount']) : null,
                    $anomaly['assignedTo'],
                    $anomaly['detectedAt'],
                    $this->now(),
                    $this->now(),
                ],
            );
        }
    }

