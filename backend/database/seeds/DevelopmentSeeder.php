    /**
     * Build six payroll periods by running the real engine over them.
     *
     * The totals are therefore the sum of the payslips, not a fudge factor.
     */
    private function seedPayrollRuns(): int
    {
        $runs = new PayrollRepository($this->app->db);
        $rules = new RuleRepository($this->app->db);
        $service = new PayrollService(
            $this->app,
            $runs,
            new EmployeeRepository($this->app->db),
            new UserRepository($this->app->db),
            $rules,
            new PayrollCalculator($this->app->db, $rules),
            new AuditLogger($this->app->db),
        );

        $adminId = (int) ($this->app->db->selectOne("SELECT id FROM users WHERE role = 'admin' LIMIT 1")['id'] ?? 0);
        $financeId = (int) ($this->app->db->selectOne("SELECT id FROM users WHERE role = 'finance' LIMIT 1")['id'] ?? 0);

        $periods = self::PAYROLL_PERIODS;
        foreach ($periods as [$year, $month]) {
            $service->createRun($year, $month, $financeId);
            $id = 'PR-' . $year . str_pad((string) $month, 2, '0', STR_PAD_LEFT);
            $service->calculate($id, $financeId);
            $service->submit($id, $financeId);
            $service->approve($id, $adminId);
            $service->finalize($id, $adminId);
        }

        return count($periods);
    }

