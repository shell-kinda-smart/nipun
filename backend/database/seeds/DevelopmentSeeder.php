            $byRole[(string) $user['role']] = $user;
        }
        if ($byRole === []) {
            return 0;
        }

        $entries = [
            ['2026-09-30 18:12:00', 'admin', 'payroll.finalized', 'payroll_run', 'PR-202609', 'Finalised the September 2026 payroll run'],
            ['2026-09-30 18:04:00', 'finance', 'payroll.approved', 'payroll_run', 'PR-202609', 'Approved the September 2026 payroll run'],
            ['2026-09-30 17:55:00', 'finance', 'payroll.processed', 'payroll_run', 'PR-202609', 'Calculated 51 payslips for September 2026'],
            ['2026-09-30 17:41:00', 'hr', 'employee.updated', 'employee', 'EMP036', 'Updated the department assignment'],
            ['2026-09-29 11:20:00', 'admin', 'settings.updated', 'user', 'admin@paylens.co', 'Changed the notification preferences'],
            ['2026-09-28 16:02:00', 'hr', 'employee.created', 'employee', 'EMP051', 'Onboarded a new employee'],
            ['2026-09-28 09:35:00', 'finance', 'report.generated', 'report', 'monthly_payroll', 'Exported the monthly payroll report'],
            ['2026-09-27 14:18:00', 'finance', 'salary.changed', 'employee', 'EMP014', 'Recorded a compensation revision effective 2026-10-01'],
            ['2026-09-26 10:44:00', 'admin', 'anomaly.resolved', 'anomaly', 'A007', 'Resolved a bank account mismatch'],
